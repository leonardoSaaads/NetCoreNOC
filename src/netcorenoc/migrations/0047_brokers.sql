-- An element is (broker, address): two customers' private ranges may both hold 10.0.0.1.
ALTER TABLE ne ADD COLUMN broker_id integer NOT NULL DEFAULT 1 REFERENCES broker (id);
ALTER TABLE ne DROP CONSTRAINT ne_ip_key;
ALTER TABLE ne ADD CONSTRAINT ne_broker_ip_key UNIQUE (broker_id, ip);
CREATE INDEX idx_ne_ip ON ne (ip);

-- A situation is one broker's: the correlator that formed it saw only that broker's traps.
ALTER TABLE situation ADD COLUMN broker_id integer NOT NULL DEFAULT 1 REFERENCES broker (id);
CREATE INDEX idx_situation_broker ON situation (broker_id, status);

-- A window is scheduled for one broker; NULL is every broker (every window from before this).
ALTER TABLE maintenance_window ADD COLUMN broker_id integer REFERENCES broker (id);
CREATE INDEX idx_mw_broker ON maintenance_window (broker_id, starts_at);

-- Each broker has its own decider (mode, pin), judge's decisions, site models and searches.
ALTER TABLE decider_setting ADD COLUMN broker_id integer NOT NULL DEFAULT 1 REFERENCES broker (id);
CREATE INDEX idx_decider_setting_broker ON decider_setting (broker_id, id);
ALTER TABLE league_decision ADD COLUMN broker_id integer NOT NULL DEFAULT 1 REFERENCES broker (id);
CREATE INDEX idx_league_decision_broker ON league_decision (broker_id, id);
ALTER TABLE model_version ADD COLUMN broker_id integer NOT NULL DEFAULT 1 REFERENCES broker (id);
CREATE INDEX idx_model_version_broker ON model_version (broker_id, kind, id);
ALTER TABLE search_run ADD COLUMN broker_id integer NOT NULL DEFAULT 1 REFERENCES broker (id);

-- Learned co-occurrence is the network's own: class and element affinities, lead precedence and
-- episodes are kept per broker. The trap catalogue's knowledge (raise/clear pairs) stays under the
-- Default broker and is shared by all.
ALTER TABLE edge ADD COLUMN broker_id integer NOT NULL DEFAULT 1;
ALTER TABLE edge DROP CONSTRAINT edge_pkey;
ALTER TABLE edge ADD PRIMARY KEY (kind, broker_id, a_id, b_id);
ALTER TABLE episode_pair ADD COLUMN broker_id integer NOT NULL DEFAULT 1;
ALTER TABLE episode_pair DROP CONSTRAINT episode_pair_pkey;
ALTER TABLE episode_pair ADD PRIMARY KEY (broker_id, kind, k);
