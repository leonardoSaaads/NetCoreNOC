-- 0047: brokers — one appliance, many networks (ADRs #494-#499). Forward-only.
--
-- A **broker** is one monitored network, owned by one customer (`organization`). A customer may
-- have several: "Claro Brasil" with a broker for the North-East and one for the South. Until now
-- every trap belonged to one network: one correlation window, one learned co-occurrence, one
-- champion model, one map. From here a network element is **(broker, address)**, a situation never
-- spans two brokers, and each broker has its own learned state, decider and judge.
--
-- How a trap reaches a broker is chosen when the broker is created (`intake`):
--
-- * `port`  — its own UDP port on this server (`udp_port`); on the standard port its `networks`
--   still claim matching sources. Repeated addresses across brokers are fine on its own port.
-- * `proxy` — a remote NetCoreNOC proxy forwards its traps over HTTPS with a token; only the
--   token's SHA-256 is kept (`proxy_token_hash`), the token is shown once. `proxy_seq` is the last
--   record accepted from the proxy's spool `proxy_stream`, so a batch the proxy sends twice (its
--   link dropped before our answer) is not spooled twice.
-- * `cidr`  — only its `networks`, on the standard port; the longest prefix wins.
--
-- The **Default broker** (id 1) holds every element, situation and learned row that existed before
-- this migration, and every trap no other broker claims.

CREATE TABLE broker (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             text COLLATE "C" NOT NULL UNIQUE CHECK (length(name) BETWEEN 1 AND 80),
    slug             text COLLATE "C" NOT NULL UNIQUE CHECK (length(slug) BETWEEN 1 AND 80),
    organization_id  integer          NOT NULL REFERENCES organization (id),
    description      text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(description) <= 2000),
    intake           text COLLATE "C" NOT NULL CHECK (intake IN ('port', 'proxy', 'cidr')),
    udp_port         integer UNIQUE CHECK (udp_port IS NULL OR udp_port BETWEEN 1024 AND 65535),
    -- Canonical CIDRs, comma-separated ('' for none); `engine/operate/routing.py` parses them.
    networks         text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(networks) <= 8000),
    proxy_token_hash text COLLATE "C",
    proxy_token_hint text COLLATE "C" CHECK (proxy_token_hint IS NULL OR length(proxy_token_hint) <= 8),
    proxy_seq        bigint           NOT NULL DEFAULT 0 CHECK (proxy_seq >= 0),
    -- The proxy's spool the numbers belong to: a reinstalled proxy starts a new stream at 1.
    proxy_stream     text COLLATE "C" CHECK (proxy_stream IS NULL OR length(proxy_stream) <= 64),
    proxy_seen_at    timestamptz,
    proxy_address    text COLLATE "C" CHECK (proxy_address IS NULL OR length(proxy_address) <= 64),
    proxy_version    text COLLATE "C" CHECK (proxy_version IS NULL OR length(proxy_version) <= 40),
    is_default       boolean          NOT NULL DEFAULT false,
    enabled          boolean          NOT NULL DEFAULT true,
    created_at       timestamptz      NOT NULL,
    created_by       text COLLATE "C" NOT NULL,
    updated_at       timestamptz      NOT NULL,
    updated_by       text COLLATE "C" NOT NULL,
    -- A broker on its own port has one; no other broker has one.
    CHECK ((intake = 'port') = (udp_port IS NOT NULL)),
    -- A proxy broker always has a token; no other broker does.
    CHECK ((intake = 'proxy') = (proxy_token_hash IS NOT NULL)),
    -- The default broker takes the standard port's unclaimed traps; it cannot be switched off.
    CHECK (NOT is_default OR (intake = 'cidr' AND enabled))
);
CREATE UNIQUE INDEX ux_broker_default ON broker (is_default) WHERE is_default;
CREATE INDEX idx_broker_organization ON broker (organization_id);

