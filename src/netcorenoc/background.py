"""The registered background set for attribution — data, and its provenance.

`PREREGISTRATION-0.14.0.md` §3 fixes this set **before any model existed** and forbids varying it
afterwards:

> the feature vectors of the `MAX_CANDIDATES`-bounded evaluation set of the fixed eval corpus,
> deduplicated and sorted, from which a deterministic sample of at most 256 rows is drawn by taking
> every `k`-th row. The base value is the model's mean output over that background set.

## Why the rows are a constant here rather than read from `eval/` at run time

Three reasons, and the first two are structural.

* **`model_version` must be pure.** It parses, validates and constructs a `LinkScorer`, touching no
  store, no clock and no filesystem — which is what lets the load path call it without acquiring
  anything. `scorer_for` builds an attribution table, so the background it builds against cannot be
  a file read.
* **`eval/` is not shipped.** It is a development directory, absent from the wheel
  (`pyproject.toml`'s `package-data` lists `migrations`, `ui` and `py.typed`). An appliance in a
  container has no corpus to read, and a background set that existed only on a developer's machine
  would make `params_hash` mean different things in different places.
* **A registered constant is checkable.** `tests/test_attribution.py` regenerates these rows from
  the corpus and compares them, so the claim *"this is the corpus's evaluation set"* is a test
  rather than a sentence.

## How they were produced, and how to reproduce them

One `Engine`, one `Store`, every `eval/corpus/*.json` scenario in sorted order an hour of synthetic
time apart, with a recording `LinkScorer` capturing every `LinkFeatures` the correlator built — so
the set is exactly what `correlate.process` evaluated, already bounded by `MAX_CANDIDATES`. Each is
converted through `challenger.feature_vector`, **the one place a feature vector is built**, then
deduplicated, sorted, and sampled every `k`-th row.

    evaluated pairs   194 341
    distinct vectors  133 202
    stride k                521   (ceil(133202 / 256))
    background rows         256

No RNG anywhere: the corpus order is `sorted(glob)`, the replay is deterministic, the dedup is a
set that is then **sorted**, and the sample is a slice. Two runs produce identical bytes.

## What this set is NOT

It is not a sample of any customer's traffic, and no claim here depends on it being one. It is a
**fixed reference distribution** against which every model's attribution is computed, so that two
models are explained against the same background and their per-feature contributions are
comparable. Changing it would change every `base_value` and therefore every `params_hash` in the
registry, which is why the plan fixes it and this module records that it is fixed.
"""

